/**
 * Normalize and tokenize a string for fuzzy matching (case-insensitive, split on non-alpha).
 */
function tokenize(s: string): string[] {
  return s
    .toLowerCase()
    .replace(/\s+/g, " ")
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
}

/**
 * Search the mock index by text (fuzzy match on title, subtitle, description) and optional entity type.
 * Each query token must appear in at least one of title, subtitle, or description (substring match).
 * If entityType is provided and not "all", only that type is returned.
 */
export function searchMockIndex(
  text: string,
  entityType?: SearchEntityType | "all"
): SearchResult[] {
  const trimmed = text.trim();
  let candidates = MOCK_SEARCH_INDEX;

  if (entityType && entityType !== "all") {
    candidates = candidates.filter((r) => r.entityType === entityType);
  }

  if (!trimmed) {
    return candidates;
  }

  const queryTokens = tokenize(trimmed);

  return candidates.filter((r) => {
    const titleTokens = tokenize(r.title);
    const subtitleTokens = r.subtitle ? tokenize(r.subtitle) : [];
    const descTokens = r.description ? tokenize(r.description) : [];
    const allTokens = [...titleTokens, ...subtitleTokens, ...descTokens];
    return queryTokens.every((qt) =>
      allTokens.some((tt) => tt.includes(qt) || (qt.length >= 2 && tt.startsWith(qt)))
    );
  });
}
